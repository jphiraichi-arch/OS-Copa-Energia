def test_indices_e_constraints_existem(banco):
    insp = inspect(db.obter_engine())
    indices_os = {i["name"]: i["column_names"] for i in insp.get_indexes("ordens_servico")}
    assert indices_os["ix_ordens_servico_filial_id_status"] == ["filial_id", "status"]
    assert indices_os["ix_ordens_servico_criado_em"] == ["criado_em"]
    indices_ev = {i["name"]: i["column_names"] for i in insp.get_indexes("os_eventos")}
    assert indices_ev["ix_os_eventos_os_id"] == ["os_id"]
    checks = {c["name"] for c in insp.get_check_constraints("ordens_servico")}
    assert checks == {
        "ck_ordens_servico_valor_previsto_nao_negativo",
        "ck_ordens_servico_tempo_previsto_positivo",
    }


