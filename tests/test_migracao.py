from datetime import UTC, datetime

from alembic import command
from sqlalchemy import MetaData, inspect, select

from osapp import db
from tests.conftest import config_alembic

TABELAS = {"filiais", "usuarios", "ordens_servico", "os_eventos"}


def _tabelas() -> set[str]:
    db.reiniciar()
    return set(inspect(db.obter_engine()).get_table_names())


def test_upgrade_e_downgrade(banco_vazio):
    cfg = config_alembic()
    command.upgrade(cfg, "head")
    assert TABELAS <= _tabelas()
    command.downgrade(cfg, "base")
    assert not (TABELAS & _tabelas())
    command.upgrade(cfg, "head")  # e sobe de novo depois de descer
    assert TABELAS <= _tabelas()


